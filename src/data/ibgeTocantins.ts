export function normalizeCityName(str: string): string {
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, '');
}

export function getIbgeCity(cityName?: string): IbgeCity | undefined {
  if (!cityName) return undefined;
  const target = normalizeCityName(cityName);
  return TOCANTINS_IBGE_CITIES.find(c => normalizeCityName(c.name) === target);
}
